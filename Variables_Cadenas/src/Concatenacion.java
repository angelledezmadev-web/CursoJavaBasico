public class Concatenacion {
    public static void main(String[] args) {

        String saludo = "hola";
        String nombre = "mundo";
        String mensaje = saludo + " " + nombre;
        System.out.println("mensaje = " + mensaje);

        var numero1 = 5;
        var numero2 = 6;
        var suma = numero1 + numero2;
        System.out.println("suma = " + suma);

    }
}

