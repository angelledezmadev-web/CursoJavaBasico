public class OperadoresComparacion {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println("Igual a: " + (a == b)); // Salida: false
        System.out.println("No igual a: " + (a != b)); // Salida: true
        System.out.println("Mayor que: " + (a > b)); // Salida: true
        System.out.println("Menor que: " + (a < b)); // Salida: false
        System.out.println("Mayor o igual que: " + (a >= b)); // Salida: true
        System.out.println("Menor o igual que: " + (a <= b)); // Salida: false
    }
}
