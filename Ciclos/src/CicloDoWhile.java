public class CicloDoWhile {
    public static void main(String[] args) {
        // Bucle DO-WHILE
        int i = 10;
        do {
            System.out.println("DO-WHILE: " + i);
            i++;
        } while (i <= 15);
// Resultado: Imprime "DO-WHILE: 10" una vez, y luego se detiene.
    }
}
