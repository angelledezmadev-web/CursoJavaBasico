public class OperadoresAritmeticos {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;
        System.out.println("Suma: " + (a + b)); // Salida: Suma: 13
        System.out.println("Resta: " + (a - b)); // Salida: Resta: 7
        System.out.println("Multiplicación: " + (a * b)); // Salida: Multiplicación: 30
        System.out.println("División: " + (a / b)); // Salida: División: 3
        System.out.println("Módulo: " + (a % b)); // Salida: Módulo: 1
    }
}
