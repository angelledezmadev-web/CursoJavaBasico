public class OperadoresLogicos {
    public static void main(String[] args) {
        boolean x = true;
        boolean y = false;
        System.out.println("AND lógico: " + (x && y)); // Salida: false
        System.out.println("OR lógico: " + (x || y)); // Salida: true
        System.out.println("NOT lógico: " + (!x)); // Salida: false
    }
}